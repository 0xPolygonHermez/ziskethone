// selftest_sha256_zisk.cpp — on-emulator self-test of the SHA-256 layer.
//
// Exercises the sha256f precompile (CSR 0x805) path by hashing known inputs and
// comparing to the FIPS 180-4 KAT digests — validating the state/block word
// packing end-to-end. Each check sets one result bit (slot 0; slot 1 = count).
// Built as sha256_selftest.elf.
// Run: ziskemu -e sha256_selftest.elf -i <8-byte len=0> -o out.

#include <cstdint>
#include <cstring>
#include "../sha256_impl.hpp"
#include "zeg/zisk_io.hpp"

using namespace zeg::sh2;

static uint32_t g_results = 0;
static int g_bit = 0;
static void rec(bool ok) { if (ok) g_results |= (1u << g_bit); ++g_bit; }

static bool dig_eq(const uint8_t* data, unsigned len, const uint8_t want[32]) {
    uint8_t d[32]; sha256(d, data, len);
    return std::memcmp(d, want, 32) == 0;
}

int main() {
    // sha256("")
    static const uint8_t E[32] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
        0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55};
    rec(dig_eq((const uint8_t*)"", 0, E));                        // bit0

    // sha256("abc")
    static const uint8_t ABC[32] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
        0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad};
    rec(dig_eq((const uint8_t*)"abc", 3, ABC));                   // bit1

    // sha256 of 56 'a' (length 56 forces a two-block padding) — boundary case.
    static const uint8_t A56[32] = {
        0xb3,0x54,0x39,0xa4,0xac,0x6f,0x09,0x48,0xb6,0xd6,0xf9,0xe3,0xc6,0xaf,0x0f,0x5f,
        0x59,0x0c,0xe2,0x0f,0x1b,0xde,0x70,0x90,0xef,0x79,0x70,0x68,0x6e,0xc6,0x73,0x8a};
    uint8_t a56[56]; std::memset(a56, 'a', 56);
    rec(dig_eq(a56, 56, A56));                                    // bit2

    // sha256 of 100 'a' (multi-block, >64).
    static const uint8_t A100[32] = {
        0x28,0x16,0x59,0x78,0x88,0xe4,0xa0,0xd3,0xa3,0x6b,0x82,0xb8,0x33,0x16,0xab,0x32,
        0x68,0x0e,0xb8,0xf0,0x0f,0x8c,0xd3,0xb9,0x04,0xd6,0x81,0x24,0x6d,0x28,0x5a,0x0e};
    uint8_t a100[100]; std::memset(a100, 'a', 100);
    rec(dig_eq(a100, 100, A100));                                 // bit3

    zeg::zisk::set_output_u32(0, g_results);
    zeg::zisk::set_output_u32(1, (uint32_t)g_bit);
    return 0;
}
